def validate(outputs, layout, walks, source, check_files):
    checks = 0
    failures = []

    def check(condition, message):
        nonlocal checks
        checks += 1
        if not condition:
            failures.append(message)

    city = layout["scenes"]["chengdu_city"]
    definition = walks["scenes"]["chengdu_city"]
    lots = city["buildings"]
    obstacles = definition["obstacles"]
    grown = [grow(box, RADIUS) for box in obstacles]
    floor = definition["floor"]
    check(definition["size"] == WORLD and definition["floor"] == FLOOR, "nine-times-area dimensions")
    check(len(lots) == len(obstacles) < 1024, "visible/collision one-to-one and bounded")
    check(len({lot["id"] for lot in lots}) == len(lots), "unique collision identities")
    check(sum(bool(lot.get("individual_house")) for lot in lots) >= 550, "at least550 independently blocked normal-size houses")
    check(len(definition["interactions"]) == 16, "original sixteen outdoor interactions")
    for lot, box in zip(lots, obstacles):
        check(lot["bounds"] == box, "visible collision mismatch: " + lot["id"])
        check(floor[0] <= box[0] and floor[1] <= box[1] and box[0] + box[2] <= floor[0] + floor[2] and box[1] + box[3] <= floor[1] + floor[3], "lot outside floor: " + lot["id"])
        if lot.get("individual_house"):
            check(170 <= box[2] <= 225 and 160 <= box[3] <= 225, "house scaled rather than added: " + lot["id"])
    for i, lot in enumerate(lots):
        for other in lots[i + 1:]:
            # River corners intentionally touch, while actual solids must not
            # overlap each other or hide new houses under landmark compounds.
            check(not overlaps(lot["bounds"], other["bounds"]), "overlapping lots: " + lot["id"] + "/" + other["id"])

    def legal(point):
        return (floor[0] <= point[0] < floor[0] + floor[2] and floor[1] <= point[1] < floor[1] + floor[3]
                and not any(contains(box, point) for box in grown))

    def clear(a, b):
        return legal(a) and legal(b) and not any(line_hits(a, b, box) for box in grown)

    for name, point in {"spawn": definition["spawn"], **definition["entries"]}.items():
        check(legal(point), "illegal entry: " + name)
    for name, item in definition["interactions"].items():
        check(legal(item["position"]), "illegal interaction: " + name)
        old = read(BASE / "walks.json")["scenes"]["chengdu_city"]["interactions"][name]
        check({k: v for k, v in item.items() if k != "position"} == {k: v for k, v in old.items() if k != "position"}, "interaction contract changed: " + name)
    for region in city["regions"]:
        check(legal(region["visit_point"]) and contains(region["bounds"], region["visit_point"]), "illegal/outside region visit: " + region["id"])
    for name, points in city["route_waypoints"].items():
        for index, (a, b) in enumerate(zip(points, points[1:])):
            check(clear(a, b), "blocked authored route: " + name + "/" + str(index))
    for bridge in city["bridges"]:
        b = bridge["bounds"]
        c = center(b)
        a, z = ([c[0], b[1]], [c[0], b[1] + b[3]]) if bridge["axis"] == "north_south" else ([b[0], c[1]], [b[0] + b[2], c[1]])
        check(clear(a, z), "bridge not radius-safe: " + bridge["id"])
    for gate in city["gates"]:
        b = gate["bounds"]
        c = center(b)
        a, z = ([c[0], b[1]], [c[0], b[1] + b[3]]) if gate["axis"] == "north_south" else ([b[0], c[1]], [b[0] + b[2], c[1]])
        check(clear(a, z), "gate not radius-safe: " + gate["id"])
    check(walks["scenes"]["chengdu_teahouse"] == read(BASE / "walks.json")["scenes"]["chengdu_teahouse"], "original tea interior changed")
    for pack, digests in source["protected_package_json_sha256"].items():
        for name, expected in digests.items():
            check(sha((ROOT / "games" / pack / name).read_bytes()) == expected, "protected old content changed: " + pack + "/" + name)
    for name, expected in source["protected_layout_sha256"].items():
        check(sha((ROOT / name).read_bytes()) == expected, "protected old layout changed: " + name)
    for name in source["unchanged_files"]:
        check(outputs[PACK / name] == (BASE / name).read_bytes(), "retained authored content changed: " + name)
    if check_files:
        for path, data in outputs.items():
            check(path.exists() and path.read_bytes() == data, "generated bytes differ: " + str(path.relative_to(ROOT)))

    # Independent raster/flood checker. Centers and closed radius-expanded
    # obstacles match the runtime contract; every legal grid cell must join the
    # ordinary arrival, not merely the hand-picked landmarks.
    width, height = math.ceil(floor[2] / CELL), math.ceil(floor[3] / CELL)
    ox, oy = floor[0] + CELL / 2, floor[1] + CELL / 2
    blocked = bytearray(width * height)
    for box in grown:
        x0, x1 = max(0, math.ceil((box[0] - ox) / CELL)), min(width - 1, math.floor((box[0] + box[2] - ox) / CELL))
        y0, y1 = max(0, math.ceil((box[1] - oy) / CELL)), min(height - 1, math.floor((box[1] + box[3] - oy) / CELL))
        for y in range(y0, y1 + 1):
            start = y * width + x0
            blocked[start:start + x1 - x0 + 1] = b"\1" * (x1 - x0 + 1)
    start = round((definition["spawn"][1] - oy) / CELL) * width + round((definition["spawn"][0] - ox) / CELL)
    reached = bytearray(width * height)
    queue = deque([start])
    reached[start] = 1
    count = 0
    while queue:
        current = queue.popleft()
        count += 1
        x, y = current % width, current // width
        neighbors = []
        if x: neighbors.append(current - 1)
        if x + 1 < width: neighbors.append(current + 1)
        if y: neighbors.append(current - width)
        if y + 1 < height: neighbors.append(current + width)
        for neighbor in neighbors:
            if not blocked[neighbor] and not reached[neighbor]:
                reached[neighbor] = 1
                queue.append(neighbor)
    legal_count = len(blocked) - sum(blocked)
    check(count == legal_count, "legal lattice disconnected: " + str(count) + "/" + str(legal_count))
    return {"checks": checks, "failures": failures, "status": "PASS" if not failures else "FAIL",
            "world_size": WORLD, "grid_size": [width, height], "grid_cell_size": CELL, "actor_radius": RADIUS,
            "legal_grid_cells": legal_count, "reachable_grid_cells": count,
            "geometry_counts": dict(Counter(lot["kind"] for lot in lots)), "scale_summary": city["scale_summary"],
            "generated_sha256": {str(path.relative_to(ROOT)): sha(data) for path, data in outputs.items()},
            "protected_package_json_sha256": source["protected_package_json_sha256"], "protected_layout_sha256": source["protected_layout_sha256"],
            "verification_boundary": "Independent standard-library geometry/lattice/static bytes check; no Godot build, actual navigation, rendered UI, browser or user acceptance is implied."}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Compare generated files without writing")
    parser.add_argument("--report", type=Path, help="Write static-check receipt under .local")
    args = parser.parse_args()
    outputs, layout, walks, source = make_content()
    result = validate(outputs, layout, walks, source, args.check)
    if not args.check and not result["failures"]:
        for path, data in outputs.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    if args.report:
        args.report.parent.mkdir(parents=True, exist_ok=True)
        args.report.write_bytes(encoded(result))
    print(json.dumps({key: result[key] for key in ("status", "checks", "failures", "scale_summary", "legal_grid_cells", "reachable_grid_cells")}, ensure_ascii=False))
    return 1 if result["failures"] else 0



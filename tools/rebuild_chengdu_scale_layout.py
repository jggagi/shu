def read(path):
    return json.loads(path.read_text(encoding="utf-8"))


def encoded(data):
    return (json.dumps(data, ensure_ascii=False, indent=2) + "\n").encode("utf-8")


def sha(data):
    return hashlib.sha256(data).hexdigest()


def overlaps(a, b):
    return a[0] < b[0] + b[2] and a[0] + a[2] > b[0] and a[1] < b[1] + b[3] and a[1] + a[3] > b[1]


def grow(box, amount):
    x, y, w, h = box
    return [x - amount, y - amount, w + amount * 2, h + amount * 2]


def center(box):
    return [box[0] + box[2] // 2, box[1] + box[3] // 2]


def contains(box, point):
    return box[0] <= point[0] <= box[0] + box[2] and box[1] <= point[1] <= box[1] + box[3]


def scale_point(point):
    return [int(n * 3) for n in point]


def line_hits(a, b, box):
    first, last = 0.0, 1.0
    for axis in (0, 1):
        direction = b[axis] - a[axis]
        if direction == 0:
            if a[axis] < box[axis] or a[axis] > box[axis] + box[axis + 2]:
                return False
            continue
        u = (box[axis] - a[axis]) / direction
        v = (box[axis] + box[axis + 2] - a[axis]) / direction
        first, last = max(first, min(u, v)), min(last, max(u, v))
        if first > last:
            return False
    return True


def stroke(a, b, width=210):
    assert a[0] == b[0] or a[1] == b[1]
    if a[0] == b[0]:
        return [a[0] - width // 2, min(a[1], b[1]) - width // 2, width, abs(b[1] - a[1]) + width]
    return [min(a[0], b[0]) - width // 2, a[1] - width // 2, abs(b[0] - a[0]) + width, width]


